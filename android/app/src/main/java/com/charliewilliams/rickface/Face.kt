data class Face(val emotion: String, @DrawableRes val image: Int)

/** Faces are bundled as rick_001.jpg … rick_106.jpg, one per emotion. */
fun Face(context: Context, index: Int): Face {
    val name = "rick_%03d".format(index + 1)
    val image = context.resources.getIdentifier(name, "drawable", context.packageName)
    require(image != 0) { "Missing drawable $name" }
    return Face(emotions[index], image)
}
